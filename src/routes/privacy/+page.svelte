		<h2>Information collected</h2>
		<p>Morelord Gaming may collect account information such as your name, email address, authentication-provider identifiers, subscription and entitlement status, Discord connection information you choose to link, Foundry installation and product-usage information needed to operate licensed tools, and information you submit through contact forms.</p>

		<h2>Google and Discord sign-in</h2>
		<p>When you sign in with Google or Discord, we receive your provider account identifier, name or display name, email address, email-verification status, and profile image when provided. We use this information to create or recognize your Morelord account. Sign-ins with the same verified email may be linked to the same account. We do not receive your Google or Discord password.</p>
		<p>Our authentication system stores provider account records and may store access tokens, refresh tokens, and related token-expiration information to support authentication. These records are separate from optional Discord role connections.</p>

		<h2>Discord membership roles</h2>
		<p>If you connect Discord from your Morelord account, we store your Discord user ID, username, display name, avatar reference, and role-synchronization status. We use your membership status to add or remove the configured Morelord roles in our Discord server. Server members may be able to see roles assigned to you.</p>
		<p>The current sign-in and role-linking flows do not request access to your Discord messages or friends list. Disconnecting Discord role linking removes the website connection and attempts to remove managed roles. It does not remove a separately linked Discord login or cancel your subscription.</p>

		<h2>Characters and Foundry installations</h2>
		<p>When you import a character, we store the submitted character data and associated image references so you can view and manage it. Connected Foundry installations may send world identifiers and names, Foundry and module versions, activation details, and validation or product-activity timestamps. This information supports activation, access checks, troubleshooting, and installation statistics.</p>

		<h2>Cookies and technical information</h2>
		<p>We use cookies for sign-in sessions and to protect authentication flows. Disabling these cookies may prevent sign-in or account features from working. Session and hosting records may include IP addresses, browser information, request details, and timestamps used for security, rate limiting, and troubleshooting.</p>

		<h2>Payments</h2>
		<p>Payment details are processed by the applicable payment provider, such as Stripe. Morelord Gaming may receive transaction, customer, subscription, and billing-status information needed to manage your membership, but does not store full payment-card numbers on this website.</p>

		<h2>How information is used</h2>
		<p>Information is used to authenticate accounts, provide purchased or entitled features, operate Foundry integrations, synchronize membership benefits, process and troubleshoot billing, respond to inquiries, maintain security, understand product adoption, and improve Morelord Gaming products and services.</p>

		<h2>Service providers</h2>
		<p>Morelord Gaming may rely on service providers for hosting, authentication, payment processing, community integrations, software distribution, and related infrastructure. Information is shared with those providers only as needed to provide the relevant service or meet legal and security obligations.</p>

		<p>Our current providers include Cloudflare for website hosting and data storage, Google and Discord for the sign-in options you choose, Stripe for billing, and Discord for community roles. Their own terms and privacy policies apply when you use their services.</p>

