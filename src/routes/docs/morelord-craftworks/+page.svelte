			<h2>Install and enable</h2>
			<ol>
				<li>Install Morelord Craftworks from the manifest URL on its product page.</li>
				<li>Install and enable the required Morelord Core and socketlib modules.</li>
				<li>Enable Morelord Craftworks in a Foundry v14 world running D&D5e 5.3 or newer.</li>
				<li>Connect Morelord Core to your Morelord Gaming account for Premium or Champion content.</li>
			</ol>
		</article>

		<article class="card docs-card">
			<div class="eyebrow">Included free</div>
			<h2>Craftworks Standard</h2>
			<p>Every user receives the core Craftworks experience, including GM-initiated gathering and harvesting, encounter loot and treasure hoards, material inventories, and searchable Materials and Recipes browsers.</p>
			<p>Standard also includes the separate <strong>SRD 5.1</strong> and <strong>SRD 5.2</strong> content packs. Campaigns can enable either rules generation independently.</p>
		</article>

		<article class="card docs-card">
			<div class="eyebrow">Tools Premium</div>
			<h2>Core source packs and crafting</h2>
			<p>Premium unlocks the complete crafting workflow and content packs backed by installed core-rule sources, including the <strong>Player's Handbook</strong> and <strong>Dungeon Master's Guide</strong>.</p>
			<p>Craftworks references the corresponding compendiums available in the world. It does not provide or replace separately licensed source books.</p>
		</article>

		<article class="card docs-card">
			<div class="eyebrow">Tools Champion</div>
			<h2>Specialized content packs</h2>
			<p>Champion is required for content packs that need source-specific data processing or workflow logic beyond normal compendium-backed recipes.</p>
			<p>The first Champion pack is <strong>Monsters of Drakkenheim</strong>, with specialized materials, monster harvesting data, recipes, acquisition content, and Drakkenheim-specific requirement resolution. The separately licensed source must also be installed and available in the world.</p>
		</article>

		<article class="card docs-card">
			<h2>Choose content packs</h2>
			<ol>
				<li>Open <strong>Configure Craftworks</strong> from the Craftworks dashboard.</li>
				<li>Open <strong>Content Packs</strong>.</li>
				<li>Enable only the packs appropriate for the campaign and its installed sources.</li>
				<li>Use <strong>Sync with Compendiums</strong> after changing installed content when an immediate refresh is needed.</li>
			</ol>
			<p>Inactive or unavailable packs contribute no materials, recipes, harvesting profiles, gathering profiles, or loot content to the world.</p>
		</article>
	</div>
</section>
